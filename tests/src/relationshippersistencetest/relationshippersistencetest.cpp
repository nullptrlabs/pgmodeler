void RelationshipPersistenceTest::recreatedFkRelationshipsFollowTheirForeignKeyWhateverTheNames()
{
	try
	{
		BaseRelationship *rel_1 = nullptr, *rel_2 = nullptr;

		// The names saved in the file are changed so they collide with the ones generated for the recreated relationships
		// (rel_<source>_<destination>, with a number when it exists): swapped, equal to the generated ones, unrelated
		struct Case { QString name_1, name_2; };
		std::vector<Case> cases = {
			{ "@2", "@1" },
			{ "@1", "@1_other" },
			{ "@2", "@2_other" },
			{ "rel_tab_c_tab_b2", "rel_tab_c_tab_b3" },
			{ "zzz", "aaa" }
		};

		for(auto &cs : cases)
		{
			DatabaseModel model, loaded;
			QString file = tmpFile("fk_rels_collision.dbm");

			model.createSystemObjects(true);
			fillModelWithFkRelationships(model, rel_1, rel_2);
			QVERIFY(rel_1 != nullptr && rel_2 != nullptr);

			rel_1->setPoints({ QPointF(1, 1) });
			rel_1->setCustomColor(QColor("#111111"));
			rel_2->setPoints({ QPointF(2, 2) });
			rel_2->setCustomColor(QColor("#222222"));

			QString name_1 = rel_1->getName(), name_2 = rel_2->getName(), content;

			model.saveModel(file, SchemaParser::XmlCode);

			// "@1" and "@2" stand for the names the relationships have in the model
			QString new_1 = QString(cs.name_1).replace("@1", name_1).replace("@2", name_2),
					new_2 = QString(cs.name_2).replace("@1", name_1).replace("@2", name_2);

			content = readFile(file);
			content.replace(QString("<relationship name=\"%1\"").arg(name_1), "<relationship name=\"@@FIRST@@\"");
			content.replace(QString("<relationship name=\"%1\"").arg(name_2), "<relationship name=\"@@SECOND@@\"");
			content.replace("@@FIRST@@", new_1);
			content.replace("@@SECOND@@", new_2);

			QFile out(file);
			QVERIFY(out.open(QIODevice::WriteOnly | QIODevice::Text));
			out.write(content.toUtf8());
			out.close();

			loadModelFile(loaded, file);

			BaseRelationship *loaded_1 = nullptr, *loaded_2 = nullptr;

			for(auto &rel : getRelationships(loaded))
			{
				if(rel->getRelationshipType() != BaseRelationship::RelationshipFk)
					continue;

				if(rel->getReferenceForeignKey()->getName() == "tab_c_fk_0")
					loaded_1 = rel;
				else if(rel->getReferenceForeignKey()->getName() == "tab_c_fk_1")
					loaded_2 = rel;
			}

			QString what = QString("%1 / %2").arg(new_1, new_2);

			QVERIFY2(loaded_1 && loaded_2, qPrintable(what));

			// The customization follows the foreign key, never the name
			QVERIFY2(loaded_1->getPoints() == std::vector<QPointF>({ QPointF(1, 1) }), qPrintable(what));
			QVERIFY2(loaded_1->getCustomColor() == QColor("#111111"), qPrintable(what));
			QVERIFY2(loaded_2->getPoints() == std::vector<QPointF>({ QPointF(2, 2) }), qPrintable(what));
			QVERIFY2(loaded_2->getCustomColor() == QColor("#222222"), qPrintable(what));

			// The names are not restored, but they remain unique among all the relationships
			std::set<QString> names;

			for(auto &rel : getRelationships(loaded))
				QVERIFY2(names.insert(rel->getName()).second, qPrintable(what + ": duplicated name " + rel->getName()));
		}
	}
	catch(Exception &e)
	{
		QFAIL(e.getExceptionsText().toStdString().c_str());
	}
}

