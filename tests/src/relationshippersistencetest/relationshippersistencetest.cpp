std::vector<BaseRelationship *> RelationshipPersistenceTest::getRelationships(DatabaseModel &model)
{
	std::vector<BaseRelationship *> rels;

	for(auto type : { ObjectType::Relationship, ObjectType::BaseRelationship })
	{
		for(unsigned idx = 0; idx < model.getObjectCount(type); idx++)
			rels.push_back(model.getRelationship(idx, type));
	}

	return rels;
}

BaseRelationship *RelationshipPersistenceTest::getRelationship(DatabaseModel &model, const QString &name)
{
	for(auto &rel : getRelationships(model))
	{
		if(rel->getName() == name)
			return rel;
	}

	return nullptr;
}

