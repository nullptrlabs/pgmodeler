void RelationshipPersistenceTest::xmlKeepsRelationshipsWithoutColumnsInReducedFormOnlyWithoutShifts()
{
	try
	{
		DatabaseModel model;
		BaseRelationship *view_rel = nullptr;
		QString xml;

		loadDemo(model);

		// The table-view relationships have no children, so their XML uses the reduced form (a single self-closed tag)
		for(auto &rel : getRelationships(model))
		{
			if(rel->getObjectType() == ObjectType::BaseRelationship &&
				 rel->getRelationshipType() == BaseRelationship::RelationshipDep)
			{
				view_rel = rel;
				break;
			}
		}

		QVERIFY(view_rel != nullptr);

		view_rel->resetSegmentShifts();
		view_rel->setPoints({});
		view_rel->resetLabelsDistance();
		view_rel->setLabelDistance(BaseRelationship::RelNameLabel, QPointF(qQNaN(), qQNaN()));
		xml = view_rel->getSourceCode(SchemaParser::XmlCode);
		QVERIFY(!xml.contains("</relationship>"));
		QVERIFY(xml.trimmed().endsWith("/>"));

		view_rel->setSegmentShifts({{ 1, shift(Qt::Horizontal, 3) }});
		xml = view_rel->getSourceCode(SchemaParser::XmlCode);
		QVERIFY(xml.contains("</relationship>"));
		QVERIFY(xml.contains("<segment "));

		view_rel->resetSegmentShifts();
		xml = view_rel->getSourceCode(SchemaParser::XmlCode);
		QVERIFY(!xml.contains("</relationship>"));
		QVERIFY(xml.trimmed().endsWith("/>"));
	}
	catch(Exception &e)
	{
		QFAIL(e.getExceptionsText().toStdString().c_str());
	}
}

