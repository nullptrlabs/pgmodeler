void RelationshipPersistenceTest::xmlIsRegeneratedWhenTheShiftsChange()
{
	try
	{
		DatabaseModel model;
		model.createSystemObjects(true);
		fillModel(model);

		BaseRelationship *rel = getRelationship(model, "rel_ab");
		QString original = rel->getSourceCode(SchemaParser::XmlCode), with_shift, changed;
		std::map<unsigned, BaseRelationship::SegmentShift> shifts;

		shifts[1] = shift(Qt::Horizontal, 10);
		rel->setSegmentShifts(shifts);
		with_shift = rel->getSourceCode(SchemaParser::XmlCode);
		QVERIFY(with_shift != original);

		shifts[1] = shift(Qt::Horizontal, 20);
		rel->setSegmentShifts(shifts);
		changed = rel->getSourceCode(SchemaParser::XmlCode);
		QVERIFY(changed != with_shift);
		QVERIFY(changed.contains("value=\"20\""));

		// Going back to no shifts gives the original code again (the cached code must be discarded)
		rel->resetSegmentShifts();
		QCOMPARE(rel->getSourceCode(SchemaParser::XmlCode), original);
	}
	catch(Exception &e)
	{
		QFAIL(e.getExceptionsText().toStdString().c_str());
	}
}

