void RelationshipPersistenceTest::setGetAndResetShifts()
{
	try
	{
		DatabaseModel model;
		model.createSystemObjects(true);
		fillModel(model);

		BaseRelationship *rel = getRelationship(model, "rel_ab");
		std::map<unsigned, BaseRelationship::SegmentShift> shifts, got;

		QVERIFY(rel != nullptr);

		shifts[1] = shift(Qt::Horizontal, -24.5);
		shifts[3] = shift(Qt::Vertical, 12);
		rel->setSegmentShifts(shifts);

		got = rel->getSegmentShifts();
		QCOMPARE(got.size(), size_t(2));
		QCOMPARE(got[1].orientation, Qt::Horizontal);
		QCOMPARE(got[1].value, -24.5);
		QCOMPARE(got[3].orientation, Qt::Vertical);
		QCOMPARE(got[3].value, 12.0);

		rel->resetSegmentShifts();
		QVERIFY(rel->getSegmentShifts().empty());

		// Resetting again is harmless
		rel->resetSegmentShifts();
		QVERIFY(rel->getSegmentShifts().empty());
	}
	catch(Exception &e)
	{
		QFAIL(e.getExceptionsText().toStdString().c_str());
	}
}

