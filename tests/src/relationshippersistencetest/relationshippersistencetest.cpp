bool RelationshipPersistenceTest::loadingFails(const QString &filename)
{
	DatabaseModel model;

	try
	{
		model.createSystemObjects(false);
		model.loadModel(filename);
	}
	catch(Exception &)
	{
		return true;
	}

	return false;
}

