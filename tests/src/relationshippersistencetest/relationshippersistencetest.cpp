void RelationshipPersistenceTest::fillModelWithFkRelationships(DatabaseModel &model, BaseRelationship *&rel_fk_1, BaseRelationship *&rel_fk_2)
{
	Table *tab_a = createTable(model, "tab_a", QPointF(0, 0)), *tab_a2 = createTable(model, "tab_a2", QPointF(0, 300)),
			*tab_b = createTable(model, "tab_b", QPointF(400, 0)), *tab_c = createTable(model, "tab_c", QPointF(800, 0));
	std::vector<Column *> generated;
	Relationship *rel_1 = new Relationship(BaseRelationship::Relationship1n, tab_a, tab_b),
			*rel_2 = new Relationship(BaseRelationship::Relationship1n, tab_a2, tab_b);

	rel_1->setName("rel_a_b");
	rel_2->setName("rel_a2_b");
	model.addRelationship(rel_1);
	model.addRelationship(rel_2);

	// The columns of tab_b created by the relationships
	for(unsigned i = 0; i < tab_b->getColumnCount(); i++)
	{
		if(tab_b->getColumn(i)->isAddedByRelationship())
			generated.push_back(tab_b->getColumn(i));
	}

	QVERIFY2(generated.size() == 2, "the relationships should have generated two columns");

	// Two foreign keys in tab_c, each one referencing one of the generated columns
	for(unsigned i = 0; i < 2; i++)
	{
		Column *col = new Column;
		Constraint *fk = new Constraint;

		col->setName(QString("ref_%1").arg(i));
		col->setType(PgSqlType("integer"));
		tab_c->addColumn(col);

		fk->setName(QString("tab_c_fk_%1").arg(i));
		fk->setConstraintType(ConstraintType::ForeignKey);
		fk->setReferencedTable(tab_b);
		fk->addColumn(col, Constraint::SourceCols);
		fk->addColumn(generated[i], Constraint::ReferencedCols);
		tab_c->addConstraint(fk);
	}

	model.updateTableFKRelationships(tab_c);

	rel_fk_1 = rel_fk_2 = nullptr;

	for(auto &rel : getRelationships(model))
	{
		if(rel->getRelationshipType() != BaseRelationship::RelationshipFk)
			continue;

		if(rel->getReferenceForeignKey()->getName() == "tab_c_fk_0")
			rel_fk_1 = rel;
		else if(rel->getReferenceForeignKey()->getName() == "tab_c_fk_1")
			rel_fk_2 = rel;
	}
}

